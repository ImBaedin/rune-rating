export function activityCategory(
  id: number,
): "activities" | "clues" | "bossing" | "minigames" {
  if (id >= 7 && id <= 13) return "clues";
  if (id >= 14 && id <= 19) return "minigames";
  if (id >= 20) return "bossing";
  return "activities";
}
